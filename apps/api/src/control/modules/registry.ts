export function getModuleDefinition(
  id: string,
): ModuleDefinition | undefined {
  return SHORTLIST_MODULE_REGISTRY.find((m) => m.id === id);
}

export function listModulesByStatus(status: ModuleDefinition["wireStatus"]) {
  return SHORTLIST_MODULE_REGISTRY.filter((m) => m.wireStatus === status);
}

export function listWiredModuleIds(): string[] {
  return listModulesByStatus("wired").map((m) => m.id);
}

export function registrySummary() {
  const wired = listModulesByStatus("wired").length;
  const stub = listModulesByStatus("stub").length;
  const blocked = listModulesByStatus("blocked").length;
  return {
    total: SHORTLIST_MODULE_REGISTRY.length,
    wired,
    stub,
    blocked,
  };
}

